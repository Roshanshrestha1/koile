// Timer functionality with persistent real-time counting
function startTimer() {
  function getNepalTime() {
    // Use browser's Intl API for real Nepal time
    return new Date(new Date().toLocaleString('en-US', { timeZone: 'Asia/Kathmandu' }));
  }

  // Fetch timer_start.txt and parse start date
  fetch('timer_start.txt?v=' + Date.now())
    .then(res => res.text())
    .then(text => {
      let startDateStr = null;
      let endDateStr = null;

      text.split('\n').forEach(line => {
        if (line.startsWith('start=')) startDateStr = line.split('=')[1].trim();
        if (line.startsWith('End=')) endDateStr = line.split('=')[1].trim();
      });

      if (!startDateStr) {
        startDateStr = getNepalTime().toISOString().slice(0, 19);
      }

      // Parse start time
      let [datePart, timePart] = startDateStr.split('T');
      let [year, month, day] = datePart.split('-').map(Number);
      let [hour, minute, second] = (timePart || '00:00:00').split(':').map(Number);

      // Nepal is UTC+5:45
      const NEPAL_OFFSET_MIN = 5 * 60 + 45;
      const utcTimestamp = Date.UTC(year, month - 1, day, hour, minute, second) - (NEPAL_OFFSET_MIN * 60 * 1000);
      const startNepalTime = new Date(utcTimestamp);

      // Parse end time if it exists
      let endNepalTime = null;
      if (endDateStr) {
        let [endDatePart, endTimePart] = endDateStr.split('T');
        let [endYear, endMonth, endDay] = endDatePart.split('-').map(Number);
        let [endHour, endMinute, endSecond] = (endTimePart || '00:00:00').split(':').map(Number);

        const endUtcTimestamp = Date.UTC(endYear, endMonth - 1, endDay, endHour, endMinute, endSecond) - (NEPAL_OFFSET_MIN * 60 * 1000);
        endNepalTime = new Date(endUtcTimestamp);
      }

      function startAccurateTimer(startNepalTime, endNepalTime) {
        function updateTimer() {
          const now = getNepalTime();

          // Check if we've passed the end time
          let isEnded = false;
          let targetTime = now;

          if (endNepalTime && now >= endNepalTime) {
            isEnded = true;
            targetTime = endNepalTime;

            // Update subtitle text when timer stops
            const timerSubtitle = document.getElementById('timerSubtitle');
            if (timerSubtitle) {
              timerSubtitle.innerText = "🌙 My waiting time has finally come to an end, and she’s back in my life 💖🥹✨";
            }
          }

          let diff = getCalendarDiff(startNepalTime, targetTime);

          if (
            diff.years < 0 ||
            diff.months < 0 ||
            diff.days < 0 ||
            diff.hours < 0 ||
            diff.minutes < 0 ||
            diff.seconds < 0
          ) {
            diff = { years: 0, months: 0, days: 0, hours: 0, minutes: 0, seconds: 0 };
          } else if (!isEnded) {
            // If not ended, do the increment logic for smooth display
            // Increment seconds by 1 to match the real clock
            diff.seconds += 1;
            if (diff.seconds === 60) {
              diff.seconds = 0;
              diff.minutes += 1;
              if (diff.minutes === 60) {
                diff.minutes = 0;
                diff.hours += 1;
                if (diff.hours === 24) {
                  diff.hours = 0;
                  diff.days += 1;
                }
              }
            }
          }

          let timerText = `⏳ ${diff.years} Year 🌟 ${diff.months} Month 📅 ${diff.days} Day ⏰ ${diff.hours} Hour 🕐 ${diff.minutes} Minute ⏱ ${diff.seconds} Second`;
          if (!isEnded) {
            timerText += " and counting...";
          } else {
            timerText += " (Stopped)";
          }

          document.getElementById('timer').innerHTML = timerText;

          if (!isEnded) {
            // Calculate ms until the next full second
            const msToNextSecond = 1000 - now.getMilliseconds();
            setTimeout(updateTimer, msToNextSecond);
          }
        }
        updateTimer();
      }

      startAccurateTimer(startNepalTime, endNepalTime);
    });
}

